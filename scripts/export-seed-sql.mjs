#!/usr/bin/env node
/**
 * Export the local JSON question bank into a Supabase SQL seed file.
 *
 * The anon key used by the app is read-only on `questions` (row level security),
 * so questions must be applied from the Supabase SQL editor or with a service
 * role key. This script keeps the SQL in sync with questions-bank/.
 *
 * Usage: node scripts/export-seed-sql.mjs [outputPath]
 * Default output: supabase/seed_questions.sql
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(process.cwd(), "questions-bank");
const OUTPUT = process.argv[2]
  ? path.resolve(process.cwd(), process.argv[2])
  : path.resolve(process.cwd(), "supabase", "seed_questions.sql");

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return entry.isFile() && entry.name.endsWith(".json") ? [full] : [];
  });
}

function readQuestions() {
  const questions = [];
  for (const file of walk(ROOT)) {
    const parsed = JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""));
    const batch = Array.isArray(parsed) ? parsed : [parsed];
    for (const q of batch) questions.push({ ...q, _file: path.relative(process.cwd(), file) });
  }
  return questions;
}

const quote = (value) => `'${String(value ?? "").replace(/'/g, "''")}'`;
const jsonb = (value) => `${quote(JSON.stringify(value ?? {}))}::jsonb`;

const questions = readQuestions();
if (questions.length === 0) {
  console.error("No questions found in questions-bank/");
  process.exit(1);
}

const statements = questions.map((q) => {
  const columns = [
    "subject",
    "major_topic",
    "subtopic",
    "vignette",
    "question",
    "options",
    "correct_answer",
    "explanation_correct",
    "explanation_incorrect",
    "difficulty",
  ].join(", ");
  const values = [
    quote(q.subject),
    quote(q.major_topic),
    quote(q.subtopic),
    quote(q.vignette),
    quote(q.question),
    jsonb(q.options),
    quote(q.correct_answer),
    quote(q.explanation_correct),
    jsonb(q.explanation_incorrect),
    quote(q.difficulty),
  ].join(",\n    ");
  return [
    `-- ${q.id} (${q._file})`,
    `insert into public.questions (${columns})`,
    `select\n    ${values}`,
    `where not exists (\n  select 1 from public.questions\n  where vignette = ${quote(q.vignette)} and question = ${quote(q.question)}\n);`,
  ].join("\n");
});

const header = [
  "-- Seed file generated by scripts/export-seed-sql.mjs. Do not edit by hand.",
  `-- ${questions.length} question(s) from questions-bank/.`,
  "-- Apply in the Supabase SQL editor (or with a service role key);",
  "-- the anon key used by the app is blocked by row level security.",
  "begin;",
  "",
].join("\n");

const footer = ["", "commit;", ""].join("\n");
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, header + statements.join("\n\n") + footer, "utf8");
console.log(`OK: ${questions.length} question(s) written to ${path.relative(process.cwd(), OUTPUT)}`);
