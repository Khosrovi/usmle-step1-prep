#!/usr/bin/env node
/**
 * Emit a single SQL file that adds the microbiology bank and its coverage plan
 * to Supabase, for the case where the service_role key is not available.
 *
 *   node scripts/export-microbiology-sql.mjs [outputPath]
 *   Default: supabase/migrations/0003_seed_microbiology.sql
 *
 * Why this exists: `questions` and `topic_coverage` have row level security with
 * no INSERT policy for `anon`, so `import-questions.mjs` is rejected with
 * 42501. The Supabase SQL editor runs as the owner, so pasting this file is
 * equivalent to the import script - and it is idempotent, so running it twice
 * (or after adding more questions) is safe.
 *
 * Deliberately scoped to Microbiology so the file stays a reasonable size and
 * cannot disturb the Biochemistry/Immunology rows already in the database.
 */
import fs from "node:fs";
import path from "node:path";

const SUBJECT = "Microbiology";
const ROOT = path.resolve(process.cwd(), "questions-bank", SUBJECT.toLowerCase());
const OUTPUT = process.argv[2]
  ? path.resolve(process.cwd(), process.argv[2])
  : path.resolve(process.cwd(), "supabase", "migrations", "0003_seed_microbiology.sql");
const PLAN_FILE = path.resolve(
  process.cwd(),
  `.cache/topic-coverage-${SUBJECT.toLowerCase()}.json`
);

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return entry.isFile() && entry.name.endsWith(".json") ? [full] : [];
  });
}

const quote = (v) => `'${String(v ?? "").replace(/'/g, "''")}'`;
const jsonb = (v) => `${quote(JSON.stringify(v ?? {}))}::jsonb`;

const questions = [];
for (const file of walk(ROOT)) {
  const parsed = JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""));
  for (const q of Array.isArray(parsed) ? parsed : [parsed]) questions.push(q);
}

const rows = questions.map((q) =>
  [
    "  (",
    `    ${quote(q.subject)}, ${quote(q.major_topic)}, ${quote(q.subtopic)},`,
    `    ${quote(q.vignette)},`,
    `    ${quote(q.question)},`,
    `    ${jsonb(q.options)},`,
    `    ${quote(q.correct_answer)},`,
    `    ${quote(q.explanation_correct)},`,
    `    ${jsonb(q.explanation_incorrect)},`,
    `    ${quote(q.difficulty)}`,
    "  )",
  ].join("\n")
);

const plan = fs.existsSync(PLAN_FILE) ? JSON.parse(fs.readFileSync(PLAN_FILE, "utf8")) : [];
const planRows = plan.map((r) =>
  `  (${quote(r.subject)}, ${quote(r.major_topic)}, ${quote(r.subtopic)}, ${r.questions_planned ?? 0}, 0, 'pending')`
);

const sql = `-- ============================================================================
--  Seed: ${SUBJECT} question bank + coverage plan
-- ============================================================================
--
--  Generated by scripts/export-microbiology-sql.mjs - do not edit by hand.
--  ${questions.length} questions across ${plan.length} planned subtopics.
--
--  HOW TO RUN
--    1. Supabase dashboard -> SQL Editor -> New query
--    2. Paste this whole file
--    3. Run
--
--  Safe to run repeatedly: questions are matched on vignette + question text,
--  and coverage rows on (subject, major_topic, subtopic).
-- ============================================================================

begin;

-- ---------------------------------------------------------------- questions
with incoming (subject, major_topic, subtopic, vignette, question, options,
               correct_answer, explanation_correct, explanation_incorrect, difficulty) as (
  values
${rows.join(",\n")}
)
insert into public.questions
  (subject, major_topic, subtopic, vignette, question, options,
   correct_answer, explanation_correct, explanation_incorrect, difficulty)
select i.subject, i.major_topic, i.subtopic, i.vignette, i.question, i.options,
       i.correct_answer, i.explanation_correct, i.explanation_incorrect, i.difficulty
from incoming i
where not exists (
  select 1 from public.questions q
  where q.vignette = i.vignette and q.question = i.question
);

-- ----------------------------------------------------------- coverage plan
with planned (subject, major_topic, subtopic, questions_planned, questions_generated, status) as (
  values
${planRows.join(",\n")}
)
insert into public.topic_coverage
  (subject, major_topic, subtopic, questions_planned, questions_generated, status)
select p.subject, p.major_topic, p.subtopic, p.questions_planned, p.questions_generated, p.status
from planned p
where not exists (
  select 1 from public.topic_coverage t
  where t.subject = p.subject
    and t.major_topic = p.major_topic
    and t.subtopic = p.subtopic
);

-- ------------------------------------------- reconcile generated counts
update public.topic_coverage t
set questions_generated = c.n,
    status = case when c.n >= t.questions_planned then 'completed' else 'pending' end
from (
  select major_topic, subtopic, count(*)::int as n
  from public.questions
  where subject = ${quote(SUBJECT)}
  group by major_topic, subtopic
) c
where t.subject = ${quote(SUBJECT)}
  and t.major_topic = c.major_topic
  and t.subtopic = c.subtopic;

commit;

-- ============================================================================
--  Verify (should report ${questions.length} and ${plan.length})
-- ============================================================================
--
--   select count(*) as microbiology_questions
--   from public.questions where subject = 'Microbiology';
--
--   select count(*) as coverage_rows, sum(questions_generated) as generated
--   from public.topic_coverage where subject = 'Microbiology';
`;

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, sql, "utf8");
const kb = (fs.statSync(OUTPUT).size / 1024).toFixed(0);
console.log(
  `OK: ${questions.length} questions + ${plan.length} coverage rows -> ${path.relative(process.cwd(), OUTPUT)} (${kb} KB)`
);
